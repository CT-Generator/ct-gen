// /api/build/[id]/yolo — fill in whatever's missing, then stitch the narrative.
//
// Two callers:
//   1. The picker's "skip the walkthrough" CTA — POSTs to a fresh row with
//      empty per_move, so this route generates all four section outputs.
//   2. The wizard's "Skip to result" button — POSTs to a row whose per_move
//      already contains some-but-not-all moves; this route generates only
//      the MISSING moves, preserves the user's earlier choices, then stitches
//      the narrative from the merged four paragraphs.
//
// Idempotent: if the row is already complete (all four moves + narrative),
// returns { ok: true, cached: true } without touching the model. If sections
// are complete but narrative is missing (rare: stepwise build whose narrative
// was moderation-flagged), generates ONLY the narrative.
//
// All-or-nothing for the per_move write: if any new section fails, nothing
// is persisted to per_move (existing entries remain untouched).

import { NextResponse } from "next/server";
import { eq } from "drizzle-orm";
import { db, schema } from "@/lib/db";
import { generateNarrative, generateSection, moderate } from "@/lib/openai";
import { type MoveKey, type WizardContent } from "@/lib/recipe";
import { getDict, isLocale, type Locale } from "@/lib/i18n";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";
export const maxDuration = 90;

const MOVE_KEYS: MoveKey[] = ["anomaly", "connection", "dismiss", "discredit"];

type Params = { id: string };
type ExistingMove = { idea: string; paragraph: string; debunk: string };

function pickRandom<T>(arr: readonly T[]): T {
  return arr[Math.floor(Math.random() * arr.length)]!;
}

export async function POST(_req: Request, { params }: { params: Promise<Params> }) {
  const { id } = await params;
  const row = (
    await db()
      .select()
      .from(schema.generations)
      .where(eq(schema.generations.shortId, id))
      .limit(1)
  )[0];
  if (!row) return NextResponse.json({ error: "Not found" }, { status: 404 });

  const content = row.recipeContent as WizardContent;
  const existingPerMove = (content.per_move ?? {}) as Partial<Record<MoveKey, ExistingMove>>;
  const missingKeys = MOVE_KEYS.filter((k) => !existingPerMove[k]);
  const haveNarrative = Boolean(content.narrative?.paragraphs?.length);

  // Idempotent short-circuit: all moves complete AND narrative present.
  if (missingKeys.length === 0 && haveNarrative) {
    return NextResponse.json({ ok: true, cached: true });
  }

  // Validate ideas are present (would have been generated by /api/start).
  // Only checked when we actually need to generate sections.
  if (missingKeys.length > 0) {
    if (
      !content.ideas ||
      !MOVE_KEYS.every((k) => Array.isArray(content.ideas?.[k]) && content.ideas[k].length > 0)
    ) {
      return NextResponse.json(
        { error: "Build is not ready — ideas missing. Run /api/start first." },
        { status: 409 },
      );
    }
  }

  const rowLocale: Locale = isLocale(row.locale) ? row.locale : "en";
  const errLabels = getDict(rowLocale).wizard;

  // Random picks ONLY for missing moves; existing moves keep the user's idea verbatim.
  const newPicks: Partial<Record<MoveKey, string>> = {};
  for (const k of missingKeys) {
    newPicks[k] = pickRandom(content.ideas![k]);
  }

  // Fan out section generation only for missing moves.
  let newSections: Partial<Record<MoveKey, { paragraph: string; debunk: string }>> = {};
  if (missingKeys.length > 0) {
    try {
      const generated = await Promise.all(
        missingKeys.map((moveKey) =>
          generateSection({
            locale: rowLocale,
            eventName: row.eventValue,
            eventSummary: content.event_intro?.paragraphs?.join("\n\n") ?? "",
            culpritName: row.culpritValue,
            motiveName: row.motiveValue,
            culpritSummary: content.culprit_summary,
            motiveSummary: content.motive_summary,
            moveKey,
            chosenIdea: newPicks[moveKey]!,
            // Yolo (full or partial) runs in parallel — no deterministic earlier-move ordering.
            prior: {},
          }),
        ),
      );
      for (let i = 0; i < missingKeys.length; i++) {
        newSections[missingKeys[i]!] = generated[i]!;
      }
    } catch (err) {
      // Breadcrumb category: section-generation failure. Includes shortId and
      // the set of missing moves so we can correlate against OpenAI status.
      // Does NOT include any model-generated text.
      console.error("[yolo] failure_category=section_generation", {
        shortId: id,
        missingMoves: missingKeys,
        errorClass: err instanceof Error ? err.name : "Unknown",
        errorMessage: err instanceof Error ? err.message : String(err),
      });
      return NextResponse.json(
        { error: errLabels.err_engine_glitched_yolo },
        { status: 502 },
      );
    }

    // Moderate only the new paragraphs (existing ones already passed moderation).
    const mods = await Promise.all(
      missingKeys.map((k) =>
        moderate(newSections[k]!.paragraph).catch(() => ({ flagged: false })),
      ),
    );

    // Soft retry for either discredit OR dismiss — both moves have a primary
    // briefing that occasionally trips OpenAI's harassment classifier (discredit
    // on classic-conspiracy archetypes; dismiss on events naming a public figure
    // with a "personal reasons" rebuttal). The soft fallbacks keep the
    // assertive conspiracist voice + unfalsifiability/incentive tells but
    // pull all targeting to institutions.
    //
    // Eligible: exactly ONE move flagged, and that move is discredit OR dismiss.
    // Otherwise fall through to the existing 422.
    const flaggedIndices = mods
      .map((m, i) => (m.flagged ? i : -1))
      .filter((i) => i >= 0);
    const SOFT_RETRY_ELIGIBLE: MoveKey[] = ["discredit", "dismiss"];
    const retryMoveKey =
      flaggedIndices.length === 1 &&
      SOFT_RETRY_ELIGIBLE.includes(missingKeys[flaggedIndices[0]!]!)
        ? (missingKeys[flaggedIndices[0]!]! as MoveKey)
        : null;

    if (flaggedIndices.length > 0 && !retryMoveKey) {
      // Multi-flag, or a single flag on a move we don't soft-retry. No recovery.
      console.warn("[yolo] failure_category=section_moderation_flag", {
        shortId: id,
        moveKey: missingKeys[flaggedIndices[0]!],
        flaggedCount: flaggedIndices.length,
      });
      return NextResponse.json(
        { error: errLabels.err_engine_refused_yolo },
        { status: 422 },
      );
    }

    if (retryMoveKey) {
      console.warn("[yolo] failure_category=soft_retry_attempted", {
        shortId: id,
        moveKey: retryMoveKey,
      });
      try {
        const softSection = await generateSection({
          locale: rowLocale,
          eventName: row.eventValue,
          eventSummary: content.event_intro?.paragraphs?.join("\n\n") ?? "",
          culpritName: row.culpritValue,
          motiveName: row.motiveValue,
          culpritSummary: content.culprit_summary,
          motiveSummary: content.motive_summary,
          moveKey: retryMoveKey,
          chosenIdea: newPicks[retryMoveKey]!,
          prior: {},
          useSoftDiscreditBriefing: retryMoveKey === "discredit",
          useSoftDismissBriefing: retryMoveKey === "dismiss",
        });
        const softMod = await moderate(softSection.paragraph).catch(() => ({
          flagged: false,
        }));
        if (softMod.flagged) {
          // Both passes flagged. Surrender to the user-facing error.
          console.warn("[yolo] failure_category=soft_retry_also_flagged", {
            shortId: id,
            moveKey: retryMoveKey,
          });
          return NextResponse.json(
            { error: errLabels.err_engine_refused_yolo },
            { status: 422 },
          );
        }
        console.log("[yolo] failure_category=soft_retry_succeeded", {
          shortId: id,
          moveKey: retryMoveKey,
        });
        newSections[retryMoveKey] = softSection;
      } catch (err) {
        console.error("[yolo] failure_category=soft_retry_error", {
          shortId: id,
          moveKey: retryMoveKey,
          errorClass: err instanceof Error ? err.name : "Unknown",
          errorMessage: err instanceof Error ? err.message : String(err),
        });
        return NextResponse.json(
          { error: errLabels.err_engine_glitched_yolo },
          { status: 502 },
        );
      }
    }
  }

  // Build the merged per_move: existing entries first (preserved verbatim), then add new entries.
  const mergedPerMove: NonNullable<WizardContent["per_move"]> = { ...existingPerMove };
  for (const k of missingKeys) {
    mergedPerMove[k] = {
      idea: newPicks[k]!,
      paragraph: newSections[k]!.paragraph,
      debunk: newSections[k]!.debunk,
    };
  }

  // Narrative finale — required for any non-cached 2xx response so the
  // /g/[id] render matches the tutored flow (standalone narrative + four-move
  // breakdown). One retry with the same inputs catches transient model
  // glitches; if the retry also fails we persist per_move only (so a
  // subsequent yolo POST hits the idempotent narrative-only recovery branch)
  // and return non-2xx so the picker/wizard surface their existing inline
  // retry control.
  const narrativeRow = {
    eventValue: row.eventValue,
    culpritValue: row.culpritValue,
    motiveValue: row.motiveValue,
    culpritSummary: content.culprit_summary,
    motiveSummary: content.motive_summary,
  };
  const firstAttempt = await attemptNarrative({
    locale: rowLocale,
    row: narrativeRow,
    mergedPerMove,
  });
  let finalAttempt = firstAttempt;
  if (firstAttempt.kind !== "ok") {
    console.warn("[yolo] failure_category=narrative_retry_attempted", {
      shortId: id,
      firstFailureKind: firstAttempt.kind,
    });
    finalAttempt = await attemptNarrative({
      locale: rowLocale,
      row: narrativeRow,
      mergedPerMove,
    });
    if (finalAttempt.kind === "ok") {
      console.log("[yolo] failure_category=narrative_retry_succeeded", {
        shortId: id,
      });
    }
  }

  if (finalAttempt.kind !== "ok") {
    const subcategory =
      finalAttempt.kind === "moderation_flagged"
        ? "moderation"
        : finalAttempt.kind === "invalid_output"
          ? "invalid_output"
          : "throw";
    console.error("[yolo] failure_category=narrative_retry_also_failed", {
      shortId: id,
      subcategory,
      ...(finalAttempt.kind === "error"
        ? {
            errorClass:
              finalAttempt.err instanceof Error
                ? finalAttempt.err.name
                : "Unknown",
            errorMessage:
              finalAttempt.err instanceof Error
                ? finalAttempt.err.message
                : String(finalAttempt.err),
          }
        : {}),
    });
    const recoverableContent: WizardContent = {
      ...content,
      per_move: mergedPerMove,
    };
    await db()
      .update(schema.generations)
      .set({ recipeContent: recoverableContent })
      .where(eq(schema.generations.shortId, id));
    if (subcategory === "moderation") {
      return NextResponse.json(
        { error: errLabels.err_engine_refused_yolo },
        { status: 422 },
      );
    }
    return NextResponse.json(
      { error: errLabels.err_engine_glitched_yolo },
      { status: 502 },
    );
  }

  const narrative: WizardContent["narrative"] = {
    paragraphs: finalAttempt.paragraphs,
    generated_at: new Date().toISOString(),
  };

  const newContent: WizardContent = {
    ...content,
    per_move: mergedPerMove,
    narrative,
  };

  await db()
    .update(schema.generations)
    .set({ recipeContent: newContent })
    .where(eq(schema.generations.shortId, id));

  return NextResponse.json({ ok: true });
}

type NarrativeAttempt =
  | { kind: "ok"; paragraphs: string[] }
  | { kind: "moderation_flagged" }
  | { kind: "invalid_output" }
  | { kind: "error"; err: unknown };

async function attemptNarrative(args: {
  locale: Locale;
  row: { eventValue: string; culpritValue: string; motiveValue: string; culpritSummary?: string; motiveSummary?: string };
  mergedPerMove: NonNullable<WizardContent["per_move"]>;
}): Promise<NarrativeAttempt> {
  try {
    const out = await generateNarrative({
      locale: args.locale,
      eventName: args.row.eventValue,
      culpritName: args.row.culpritValue,
      motiveName: args.row.motiveValue,
      culpritSummary: args.row.culpritSummary,
      motiveSummary: args.row.motiveSummary,
      paragraphs: {
        anomaly: args.mergedPerMove.anomaly!.paragraph,
        connection: args.mergedPerMove.connection!.paragraph,
        dismiss: args.mergedPerMove.dismiss!.paragraph,
        discredit: args.mergedPerMove.discredit!.paragraph,
      },
    });
    if (!Array.isArray(out.paragraphs) || out.paragraphs.length === 0) {
      return { kind: "invalid_output" };
    }
    const joined = out.paragraphs.join("\n\n");
    const mod = await moderate(joined).catch(() => ({ flagged: false }));
    if (mod.flagged) return { kind: "moderation_flagged" };
    return { kind: "ok", paragraphs: out.paragraphs };
  } catch (err) {
    return { kind: "error", err };
  }
}
